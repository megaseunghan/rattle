// QA-SCANNER-PAIR-20261118. 로컬 PGlite 가상 자료 전용; 기존 통합 fixture에서 호출한다.
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
export async function validateScannerPairing({db,users,store,otherStore,emp,member,as,migration}) {
 let checks=0;
 const check=(name,a,b)=>{assert.deepEqual(a,b,name);checks++;};
 const reject=async(name,code,fn)=>{await assert.rejects(fn,e=>e.message.includes(code),name);checks++;};
 await db.exec(await migration('20261118130000_scanner_pairing.sql'));
 const issue=async(key='owner',sid=store)=>(await as(users[key],'SELECT issue_attendance_scanner_registration($1,$2) r',[sid,'QA-매장폰'])).rows[0].r;
 const exchange=async(q,sid=store)=>(await as(null,'SELECT exchange_attendance_scanner_registration($1,$2) r',[sid,q])).rows[0].r;
 const clearLimits=()=>db.query("UPDATE private.attendance_scanner_pairing_limits SET window_start=now()-interval '2 minutes'");
 const resetIssueWindow=()=>db.exec("UPDATE private.attendance_scanner_pairings SET issued_at=now()-interval '11 minutes'");
 await reject('익명 발급 불가','permission denied',()=>as(null,'SELECT issue_attendance_scanner_registration($1,$2)',[store,'QA']));
 await reject('직원 발급 불가','ATTENDANCE_ADMIN_REQUIRED',()=>issue('regular'));
 await reject('PT 발급 불가','ATTENDANCE_ADMIN_REQUIRED',()=>issue('part'));
 await reject('타매장 발급 불가','STORE_ACCESS_DENIED',()=>issue('outside'));
 const pair=await issue();
 check('QR 유효시간 2분',Math.abs(new Date(pair.expires_at).getTime()-Date.now()-120000)<10000,true);
 check('등록 QR은 직원 출퇴근 QR과 별개',pair.registration_qr.startsWith(`rattle-scanner:v1.${store}.`),true);
 check('원문 nonce 저장 없음',(await db.query("SELECT encode(nonce_hash,'hex') h FROM private.attendance_scanner_pairings WHERE id=$1",[pair.registration_id])).rows[0].h===pair.registration_qr.split('.')[2],false);
 check('매장 불일치 거절',(await exchange(pair.registration_qr,otherStore)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_INVALID');
 const token=await exchange(pair.registration_qr);
 check('로그인 없이 등록 성공',[token.ok,token.store_id,token.token.length],[true,store,64]);
 check('스캐너 토큰으로 익명 상태 조회',(await as(null,'SELECT attendance_scanner_status($1) r',[token.token])).rows[0].r.store_name,'QA-QR-AUTO');
 check('스캐너 토큰은 계정 세션 아님',(await as(null,'SELECT auth.uid() u')).rows[0].u,null);
 await reject('토큰으로 매장 권한 변경 불가','permission denied',()=>as(null,'SELECT set_store_manager($1,$2,0)',[store,member.part]));
 check('한번 교환한 QR은 재사용 불가',(await exchange(pair.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_USED');
 check('재사용시 스캐너 중복0',(await db.query('SELECT count(*)::int n FROM attendance_scanners WHERE id=$1',[token.scanner_id])).rows[0].n,1);
 await reject('구 등록 RPC 차단','permission denied',()=>as(users.owner,'SELECT register_attendance_scanner($1,$2)',[store,'QA']));
 await reject('등록 원본 client 읽기 차단','permission denied',()=>as(users.owner,'SELECT * FROM private.attendance_scanner_pairings'));
 await reject('직원은 원격 해제 불가','ATTENDANCE_ADMIN_REQUIRED',()=>as(users.part,'SELECT revoke_attendance_scanner($1)',[token.scanner_id]));
 const device=(await as(users.regular,"SELECT register_attendance_device('QA-pair') r")).rows[0].r;
 const nonce=(await as(users.regular,'SELECT issue_attendance_qr($1) r',[device.device_id])).rows[0].r.nonce;
 const sig=createHmac('sha256',Buffer.from(device.secret,'base64')).update(`${device.device_id}.${nonce}`).digest().subarray(0,16).toString('hex');
 const employeeQr=`rattle-punch:v1.${device.device_id}.${nonce}.${sig}`;
 const punched=(await as(null,'SELECT punch_attendance($1,$2) r',[token.token,employeeQr])).rows[0].r;
 check('새 매장폰 토큰은 로그인 없이 출퇴근 기록 가능',punched.kind,'clock_in');
 await reject('등록 QR로 출퇴근 기록 불가','ATTENDANCE_QR_INVALID',()=>as(null,'SELECT punch_attendance($1,$2)',[token.token,pair.registration_qr]));
 await as(users.manager,'SELECT revoke_attendance_scanner($1)',[token.scanner_id]);
 await reject('원격 해제 다음 요청 구분','ATTENDANCE_SCANNER_REVOKED',()=>as(null,'SELECT attendance_scanner_status($1)',[token.token]));
 await reject('원격 해제 후 출퇴근 요청도 차단','ATTENDANCE_SCANNER_REVOKED',()=>as(null,'SELECT punch_attendance($1,$2)',[token.token,employeeQr]));
 // An invalid registration cannot consume or alter a valid nonce.
 check('형식 오류 거절',(await exchange('not-a-qr')).error_code,'ATTENDANCE_SCANNER_REGISTRATION_INVALID');
 const old=await issue();const fresh=await issue();
 check('새 등록 QR 발급시 이전 미사용 QR 폐기',(await exchange(old.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_INVALID');
 await db.query("UPDATE private.attendance_scanner_pairings SET expires_at=now()-interval '1 second' WHERE id=$1",[fresh.registration_id]);
 check('만료 QR 거절',(await exchange(fresh.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_EXPIRED');
 const managerPair=await issue('manager');
 const revision=(await as(users.owner,'SELECT get_my_store_access($1) r',[store])).rows[0].r.manager_revision;
 await as(users.owner,'SELECT set_store_manager($1,NULL,$2)',[store,Number(revision)]);
 check('발급 뒤 점장 해제되면 교환 차단',(await exchange(managerPair.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_FORBIDDEN');
 await resetIssueWindow();
 const ownerPair=await issue();
 await db.query('UPDATE stores SET deleted_at=now() WHERE id=$1',[store]);
 check('삭제 매장 등록 교환 차단',(await exchange(ownerPair.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_INVALID');
 await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)",[users.owner]);
 await db.query('UPDATE stores SET deleted_at=NULL WHERE id=$1',[store]);
 await clearLimits();
 // Valid-format bad nonces count against the actual QR store, not an attacker-controlled claimed store.
 const bad=`rattle-scanner:v1.${store}.${'0'.repeat(64)}`;
 for(let n=0;n<20;n++)check('유효 형식 잘못된 nonce 거절',(await exchange(bad)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_INVALID');
 check('분당21번째 교환 차단',(await exchange(ownerPair.registration_qr)).error_code,'ATTENDANCE_SCANNER_REGISTRATION_RATE_LIMIT');
 check('실패해도 rate counter 저장됨',(await db.query('SELECT attempts FROM private.attendance_scanner_pairing_limits WHERE store_id=$1',[store])).rows[0].attempts,21);
 await clearLimits();
 check('다음 윈도에서 정상 교환',(await exchange(ownerPair.registration_qr)).ok,true);
 await resetIssueWindow();
 for(let n=0;n<5;n++)await issue();
 await reject('발급도 매장별10분5회 제한','ATTENDANCE_SCANNER_REGISTRATION_RATE_LIMIT',()=>issue());
 const f=(await db.query("SELECT pg_get_functiondef('public.exchange_attendance_scanner_registration(uuid,text)'::regprocedure) d")).rows[0].d;
 check('교환 원자 잠금/권한 재검증',f.includes('FOR UPDATE')&&f.includes('scanner_pairing_issuer_allowed')&&f.indexOf('scanner_pairing_issuer_allowed')<f.indexOf('INSERT INTO public.attendance_scanners'),true);
 console.log(`PASS scanner pairing: ${checks} checks (QA-SCANNER-PAIR-20261118, PGlite, no remote).`);
}
