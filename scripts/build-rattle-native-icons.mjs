// design-system: DESIGN.md — compile reviewed SVG originals to a Metro-safe TS module.
import { readFile, readdir, writeFile } from 'node:fs/promises';
const directory = new URL('../assets/icons/navigation/', import.meta.url);
const icons = {};
for (const name of (await readdir(directory)).filter(name => name.endsWith('.svg')).sort()) {
  icons[name.slice(0, -4)] = (await readFile(new URL(name, directory), 'utf8')).trim();
}
await writeFile(new URL('../lib/icons/vectorAssets.ts', import.meta.url), '// Generated by scripts/build-rattle-native-icons.mjs. Do not edit.\nexport const vectorAssets = ' + JSON.stringify(icons, null, 2) + ' as const;\nexport type VectorAssetName = keyof typeof vectorAssets;\n');
