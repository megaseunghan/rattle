import React from 'react';
import { render, fireEvent, waitFor } from '@testing-library/react-native';
import AsyncStorage from '@react-native-async-storage/async-storage';
import { StoreSetupWizard } from '../../lib/components/StoreSetupWizard';
import { createStoreWithSetup } from '../../lib/services/stores';
jest.mock('@react-native-async-storage/async-storage', () => ({ getItem: jest.fn(), setItem: jest.fn(), removeItem: jest.fn() }));
jest.mock('expo-crypto', () => ({ randomUUID: () => 'same-request' }));
jest.mock('../../lib/services/stores', () => ({ createStoreWithSetup: jest.fn() }));
beforeEach(() => { jest.clearAllMocks(); (AsyncStorage.getItem as jest.Mock).mockResolvedValue(null); (AsyncStorage.setItem as jest.Mock).mockResolvedValue(undefined); (AsyncStorage.removeItem as jest.Mock).mockResolvedValue(undefined); });
it('사업자번호 없이 POS·공유 선택을 보존하고 재시도는 같은 요청 ID를 사용한다', async () => {
  const created = jest.fn().mockResolvedValue(undefined);
  const view = render(<StoreSetupWizard userId="owner" onCreated={created} onCancel={jest.fn()} />);
  await waitFor(() => expect(view.getByText('다음')).toBeTruthy());
  fireEvent.changeText(view.getByPlaceholderText('예: 라틀 연남점'), '연남점');
  fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('지금 연결하기')).toBeTruthy());
  fireEvent.press(view.getByText('지금 연결하기')); fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('직원에게만 공유')).toBeTruthy());
  fireEvent.press(view.getByText('직원에게만 공유')); fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('이대로 시작할까요?')).toBeTruthy());
  fireEvent.press(view.getByLabelText('POS 연결 수정'));
  expect(view.getByRole('radio', { name: /지금 연결하기/ }).props.accessibilityState.checked).toBe(true);
  fireEvent.press(view.getByText('수정 완료'));
  await waitFor(() => expect(view.getByText('이대로 시작할까요?')).toBeTruthy());
  expect(view.getByText('직원에게만 공유')).toBeTruthy();
  expect(createStoreWithSetup).not.toHaveBeenCalled();
  (createStoreWithSetup as jest.Mock).mockRejectedValueOnce(new Error('temporary')).mockResolvedValueOnce({ id: 'new-store' });
  fireEvent.press(view.getByText('매장 시작하기'));
  await waitFor(() => expect(createStoreWithSetup).toHaveBeenCalledTimes(1));
  await waitFor(() => expect(view.getByText('매장 설정을 마치지 못했어요. 다시 시도해주세요.')).toBeTruthy());
  fireEvent.press(view.getByText('매장 시작하기'));
  await waitFor(() => expect(created).toHaveBeenCalledWith('new-store', 'now'));
  expect((createStoreWithSetup as jest.Mock).mock.calls.map(call => call[0])).toEqual(Array(2).fill({ name: '연남점', posChoice: 'now', shareScope: 'regular_only', requestId: 'same-request' }));
});
it('제출된 초안을 재시작하면 요약에서 같은 설정으로 재시도할 수 있다', async () => {
  (AsyncStorage.getItem as jest.Mock).mockResolvedValue(JSON.stringify({ name: '저장 매장', pos: 'later', scope: 'none', requestId: 'original', submitted: true }));
  (createStoreWithSetup as jest.Mock).mockResolvedValue({ id: 'created', pos_setup_choice: 'later' });
  const done = jest.fn().mockResolvedValue(undefined);
  const view = render(<StoreSetupWizard userId="owner" onCreated={done} onCancel={jest.fn()} />);
  await waitFor(() => expect(view.getByText('이대로 시작할까요?')).toBeTruthy());
  expect(view.queryByText('수정')).toBeNull();
  fireEvent.press(view.getByText('매장 시작하기'));
  await waitFor(() => expect(done).toHaveBeenCalledWith('created', 'later'));
  expect(createStoreWithSetup).toHaveBeenCalledWith({ name: '저장 매장', posChoice: 'later', shareScope: 'none', requestId: 'original' });
});
it('다음 연타는 저장 중에 질문을 건너뛰지 않는다', async () => {
  let release!: () => void;
  (AsyncStorage.setItem as jest.Mock).mockImplementationOnce(() => new Promise<void>(resolve => { release = resolve; }));
  const view = render(<StoreSetupWizard userId="owner" onCreated={jest.fn()} onCancel={jest.fn()} />);
  await waitFor(() => expect(view.getByText('다음').parent?.props.accessibilityState?.disabled).not.toBe(true));
  fireEvent.changeText(view.getByPlaceholderText('예: 라틀 연남점'), '내 매장');
  const nextButton = view.getByRole('button', { name: '다음' });
  fireEvent.press(nextButton); fireEvent.press(nextButton);
  release();
  await waitFor(() => expect(view.getByText('POS는 언제 연결할까요?')).toBeTruthy());
  expect(view.queryByText('손익을 누구와 공유할까요?')).toBeNull();
});
it('이전 생성이 완료된 요청의 초안은 새 매장 등록에 재사용하지 않는다', async () => {
  (AsyncStorage.getItem as jest.Mock).mockResolvedValue(JSON.stringify({ name: '기존 생성 매장', pos: 'later', scope: 'none', requestId: 'completed-request', submitted: true }));
  const view = render(<StoreSetupWizard knownRequestIds={['completed-request']} userId="owner" onCreated={jest.fn()} onCancel={jest.fn()} />);
  await waitFor(() => expect(AsyncStorage.removeItem).toHaveBeenCalled());
  expect(view.getByText('매장 이름을 알려주세요')).toBeTruthy();
  expect(view.getByPlaceholderText('예: 라틀 연남점').props.value).toBe('');
});

it('요약에서 이름을 비우면 안내하고 빈 이름의 최종 요약으로 넘어가지 않는다', async () => {
  (AsyncStorage.getItem as jest.Mock).mockResolvedValue(JSON.stringify({ name: '원래 매장', pos: 'later', scope: 'none', requestId: 'draft' }));
  const view = render(<StoreSetupWizard userId="owner" onCreated={jest.fn()} onCancel={jest.fn()} />);
  await waitFor(() => expect(view.getByPlaceholderText('예: 라틀 연남점').props.value).toBe('원래 매장'));
  fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('POS는 언제 연결할까요?')).toBeTruthy());
  fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('손익을 누구와 공유할까요?')).toBeTruthy());
  fireEvent.press(view.getByText('다음'));
  await waitFor(() => expect(view.getByText('이대로 시작할까요?')).toBeTruthy());
  fireEvent.press(view.getByLabelText('매장 이름 수정'));
  fireEvent.changeText(view.getByPlaceholderText('예: 라틀 연남점'), '');
  fireEvent.press(view.getByText('검토로 돌아가기'));
  await waitFor(() => expect(view.getByText('매장 이름을 입력해주세요.')).toBeTruthy());
  expect(view.queryByText('매장 시작하기')).toBeNull();
  expect(createStoreWithSetup).not.toHaveBeenCalled();
});
